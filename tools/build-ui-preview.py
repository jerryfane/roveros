#!/usr/bin/env python3
"""Builds docs/ui/dot-preview.html, a self-contained animated reference of the
Dot style, from docs/ui/dot.js, docs/ui/shell.{js,css} and docs/ui/fonts/.

Usage: tools/build-ui-preview.py [--check]
  --check  exits 1 if the committed preview differs from a fresh build.
"""
import base64
import pathlib
import sys

ui = pathlib.Path(__file__).resolve().parent.parent / "docs" / "ui"
FONTS = [("Doto", "doto.woff2", "400 900"), ("Inter", "inter.woff2", "400 700")]


def build() -> str:
    faces = "".join(
        f"@font-face{{font-family:'{name}';font-weight:{weight};font-display:block;"
        f"src:url(data:font/woff2;base64,{base64.b64encode((ui / 'fonts' / file).read_bytes()).decode()}) format('woff2')}}\n"
        for name, file, weight in FONTS
    )
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>RoverOS · Dot</title>
<!-- Generated by tools/build-ui-preview.py from docs/ui/. Do not edit. -->
<style>{faces}{(ui / 'shell.css').read_text()}</style></head>
<body><div class="shell">
<div class="top"><h1>RoverOS<small>Dot · visual style reference</small></h1><button class="tour">▶ Tour</button></div>
<nav class="side"></nav>
<main class="stage"><div class="fit"><div class="phone"><div class="scr"></div></div></div>
<div class="pager"><button id="prev">‹</button><span></span><button id="next">›</button></div><p class="cap"></p></main>
</div><script>{(ui / 'shell.js').read_text()}
{(ui / 'dot.js').read_text()}</script></body></html>
"""


out = ui / "dot-preview.html"
html = build()
if "--check" in sys.argv:
    if not out.exists() or out.read_text() != html:
        sys.exit("dot-preview.html is out of date: run tools/build-ui-preview.py")
    print("dot-preview.html is up to date")
else:
    out.write_text(html)
    print(f"{out} ({len(html)} bytes)")
